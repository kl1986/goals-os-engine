HEADER = (
    "| Label | Routine | Command | Kind | Timing | Enabled | Log | Env | Options |\n"
    "|---|---|---|---|---|---|---|---|---|\n"
)

FIXED_ROW = (
    "| com.test.dashboard | Dashboard | `/usr/bin/python3 /tmp/dash.py --brain /tmp/brain` "
    "| fixed-interval | 06:05 | yes | ~/Library/Logs/dash.log ; ~/Library/Logs/dash-error.log "
    "| PATH=/usr/bin; HOME=~ | run-at-load=true |\n"
)

POLL_ROW = (
    "| com.test.sweep | Capture sweep | `/usr/bin/python3 /tmp/sweep.py` | poll | 15m | yes "
    "| /tmp/sweep.log | PATH=/usr/bin | — |\n"
)

UNMANAGED_PLIST = (
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
    '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
    '<plist version="1.0">\n<dict>\n'
    "\t<key>Label</key>\n\t<string>com.thirdparty.thing</string>\n"
    "\t<key>ProgramArguments</key>\n\t<array>\n\t\t<string>/bin/true</string>\n\t</array>\n"
    "\t<key>StartInterval</key>\n\t<integer>60</integer>\n"
    "</dict>\n</plist>\n"
)


def table(*rows):
    return HEADER + "".join(rows)


class ScheduleFixture(unittest.TestCase):
    """Every test gets its own tmp Brain and its own tmp LaunchAgents dir.

    The real ~/Library/LaunchAgents is never a target: `agents_dir` is
    injected everywhere, and `sync_schedules.DEFAULT_LAUNCH_AGENTS` is only
    ever read by `main()`.
    """

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        root = Path(self._tmp.name)
        self.brain = root / "brain"
        (self.brain / "config").mkdir(parents=True)
        self.agents_dir = root / "LaunchAgents"
        self.agents_dir.mkdir()

    def tearDown(self):
        self._tmp.cleanup()

    def write_table(self, text):
        (self.brain / "config" / "schedules.md").write_text(text)

    def sync(self, **kwargs):
        kwargs.setdefault("load", False)
        kwargs.setdefault("show_diff", False)
        return sync_schedules.sync(self.brain, self.agents_dir, **kwargs)

    def plist(self, label):
        with open(self.agents_dir / f"{label}.plist", "rb") as fh:
            return plistlib.load(fh)


class TestRowRoundTrip(ScheduleFixture):
    def test_row_round_trips_to_a_valid_managed_plist(self):
        self.write_table(table(FIXED_ROW))
        self.sync()

        path = self.agents_dir / "com.test.dashboard.plist"
        self.assertTrue(path.exists())
        self.assertTrue(sync_schedules.is_managed(path))

        data = self.plist("com.test.dashboard")
        self.assertIs(data[sync_schedules.MARKER_KEY], True)
        self.assertEqual(data["Label"], "com.test.dashboard")
        self.assertEqual(
            data["ProgramArguments"],
            ["/usr/bin/python3", "/tmp/dash.py", "--brain", "/tmp/brain"],
        )
        self.assertEqual(data["StandardOutPath"], str(Path.home() / "Library/Logs/dash.log"))
        self.assertEqual(data["StandardErrorPath"], str(Path.home() / "Library/Logs/dash-error.log"))
        self.assertEqual(data["EnvironmentVariables"], {"PATH": "/usr/bin", "HOME": str(Path.home())})
        self.assertIs(data["RunAtLoad"], True)

        text = path.read_text()
        self.assertIn("Generated by goals-os-engine scripts/sync_schedules.py", text)
        self.assertIn("config/schedules.md", text)

    def test_resync_is_idempotent_and_rewrites_nothing(self):
        self.write_table(table(FIXED_ROW))
        self.sync()
        path = self.agents_dir / "com.test.dashboard.plist"
        before = path.read_text()
        mtime = path.stat().st_mtime_ns

        plan = self.sync()
        self.assertEqual([i["label"] for i in plan["unchanged"]], ["com.test.dashboard"])
        self.assertEqual(plan["create"], [])
        self.assertEqual(plan["update"], [])
        self.assertEqual(path.read_text(), before)
        self.assertEqual(path.stat().st_mtime_ns, mtime)

    def test_changed_timing_updates_the_plist(self):
        self.write_table(table(FIXED_ROW))
        self.sync()
        self.write_table(table(FIXED_ROW.replace("| 06:05 |", "| 07:30 |")))
        plan = self.sync()
        self.assertEqual([i["label"] for i in plan["update"]], ["com.test.dashboard"])
        self.assertEqual(self.plist("com.test.dashboard")["StartCalendarInterval"],
                         {"Hour": 7, "Minute": 30})


class TestFixedIntervalRendering(ScheduleFixture):
    def test_clock_time_renders_a_single_start_calendar_interval_dict(self):
        self.write_table(table(FIXED_ROW))
        self.sync()
        data = self.plist("com.test.dashboard")
        self.assertEqual(data["StartCalendarInterval"], {"Hour": 6, "Minute": 5})
        self.assertNotIn("StartInterval", data)

    def test_weekday_range_renders_one_entry_per_day(self):
        row = ("| com.test.sonia | — | `/bin/echo hi` | fixed-interval | Mon-Fri 14:00 | yes "
               "| /tmp/s.log | — | cwd=/tmp |\n")
        self.write_table(table(row))
        self.sync()
        data = self.plist("com.test.sonia")
        self.assertEqual(
            data["StartCalendarInterval"],
            [{"Weekday": d, "Hour": 14, "Minute": 0} for d in (1, 2, 3, 4, 5)],
        )
        self.assertEqual(data["WorkingDirectory"], "/tmp")

    def test_single_named_weekday_renders_a_dict_with_weekday_zero_for_sunday(self):
        row = ("| com.test.dream | — | `/bin/echo hi` | fixed-interval | Sun 20:07 | yes "
               "| /tmp/d.log | — | — |\n")
        self.write_table(table(row))
        self.sync()
        self.assertEqual(self.plist("com.test.dream")["StartCalendarInterval"],
                         {"Weekday": 0, "Hour": 20, "Minute": 7})

    def test_cadence_word_row_renders_no_job(self):
        row = "| planning | Planning session | — | fixed-interval | weekly | yes | — | — | — |\n"
        self.write_table(table(row))
        plan = self.sync()
        self.assertEqual(plan["create"], [])
        self.assertEqual(list(self.agents_dir.iterdir()), [])


