class TestRemovedRow(ScheduleFixture):
    def test_removed_row_disables_only_its_managed_job(self):
        self.write_table(table(FIXED_ROW, POLL_ROW))
        self.sync()
        (self.agents_dir / "com.thirdparty.thing.plist").write_text(UNMANAGED_PLIST)

        self.write_table(table(FIXED_ROW))
        plan = self.sync()

        self.assertEqual([i["label"] for i in plan["remove"]], ["com.test.sweep"])
        self.assertFalse((self.agents_dir / "com.test.sweep.plist").exists())
        self.assertTrue((self.agents_dir / "com.test.dashboard.plist").exists())
        self.assertTrue((self.agents_dir / "com.thirdparty.thing.plist").exists())

    def test_disabled_row_is_removed_too(self):
        self.write_table(table(FIXED_ROW))
        self.sync()
        self.write_table(table(FIXED_ROW.replace("| yes |", "| no |")))
        plan = self.sync()
        self.assertEqual([i["label"] for i in plan["remove"]], ["com.test.dashboard"])
        self.assertFalse((self.agents_dir / "com.test.dashboard.plist").exists())


class TestUnmanagedIsUntouchable(ScheduleFixture):
    def test_unmanaged_plist_is_left_byte_identical(self):
        path = self.agents_dir / "com.thirdparty.thing.plist"
        path.write_text(UNMANAGED_PLIST)
        before = path.read_bytes()

        self.write_table(table(FIXED_ROW))
        self.sync()

        self.assertEqual(path.read_bytes(), before)

    def test_label_collision_with_an_unmanaged_plist_is_refused_before_any_write(self):
        collide = self.agents_dir / "com.test.dashboard.plist"
        collide.write_text(UNMANAGED_PLIST)
        before = collide.read_bytes()

        self.write_table(table(FIXED_ROW, POLL_ROW))
        with self.assertRaises(sync_schedules.RefusedError) as ctx:
            self.sync()

        self.assertIn("NOT Managed", str(ctx.exception))
        self.assertEqual(collide.read_bytes(), before)
        # The other, perfectly good row was not written either.
        self.assertFalse((self.agents_dir / "com.test.sweep.plist").exists())

    def test_is_managed_is_false_for_unparseable_and_unmarked_files(self):
        junk = self.agents_dir / "junk.plist"
        junk.write_text("not a plist at all")
        self.assertFalse(sync_schedules.is_managed(junk))

        unmarked = self.agents_dir / "com.thirdparty.thing.plist"
        unmarked.write_text(UNMANAGED_PLIST)
        self.assertFalse(sync_schedules.is_managed(unmarked))


class TestMalformedRows(ScheduleFixture):
    def _assert_rejected(self, row, fragment):
        self.write_table(table(FIXED_ROW, row))
        with self.assertRaises(schedules.ScheduleError) as ctx:
            self.sync()
        self.assertIn(fragment, str(ctx.exception))
        # Nothing partially written — not even the valid row above it.
        self.assertEqual(list(self.agents_dir.iterdir()), [])

    def test_unknown_kind(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | whenever | 06:00 | yes | /tmp/x.log | — | — |\n",
            "Kind must be one of",
        )

    def test_unparseable_clock_time(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | half past six | yes | /tmp/x.log | — | — |\n",
            "Timing must be",
        )

    def test_poll_row_without_an_interval(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | poll | 06:00 | yes | /tmp/x.log | — | — |\n",
            "poll Timing must be an interval",
        )

    def test_out_of_range_clock_time(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | 25:00 | yes | /tmp/x.log | — | — |\n",
            "not a valid 24h clock time",
        )

    def test_bad_enabled_value(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | 06:00 | maybe | /tmp/x.log | — | — |\n",
            "Enabled must be yes or no",
        )

    def test_unknown_option_key(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | 06:00 | yes | /tmp/x.log | — | nice=5 |\n",
            "unknown Options key",
        )

    def test_wrong_cell_count(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | 06:00 | yes |\n",
            "expected 9",
        )

    def test_duplicate_label(self):
        self.write_table(table(FIXED_ROW, FIXED_ROW))
        with self.assertRaises(schedules.ScheduleError) as ctx:
            self.sync()
        self.assertIn("duplicate Label", str(ctx.exception))
        self.assertEqual(list(self.agents_dir.iterdir()), [])

    def test_enabled_fixed_interval_job_needs_a_clock_not_a_cadence_word(self):
        self._assert_rejected(
            "| com.test.x | — | `/bin/echo hi` | fixed-interval | weekly | yes | /tmp/x.log | — | — |\n",
            "needs a clock time in Timing",
        )

    def test_every_problem_is_reported_not_just_the_first(self):
        self.write_table(table(
            "| com.test.a | — | `/bin/echo hi` | whenever | 06:00 | yes | /tmp/a.log | — | — |\n",
            "| com.test.b | — | `/bin/echo hi` | fixed-interval | nonsense | yes | /tmp/b.log | — | — |\n",
        ))
        with self.assertRaises(schedules.ScheduleError) as ctx:
            self.sync()
        problems = "\n".join(ctx.exception.problems)
        self.assertIn("line 3", problems)  # both bad rows are named, not just the first
        self.assertIn("line 4", problems)
        self.assertIn("Kind must be one of", problems)
        self.assertIn("Timing must be", problems)

    def test_missing_schedules_file_fails_loudly(self):
        with self.assertRaises(schedules.ScheduleError) as ctx:
            self.sync()
        self.assertIn("does not exist", str(ctx.exception))


