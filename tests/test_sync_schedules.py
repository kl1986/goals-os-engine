class TestHeartbeatReadsCadenceFromSchedules(ScheduleFixture):
    """ADR-0030: cadence left the Engine; heartbeat.py reads it from the Brain."""

    def _routine_state(self, **rows):
        lines = ["| Routine | Last run |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in rows.items()]
        (self.brain / "config" / "routine-state.md").write_text("\n".join(lines) + "\n")

    def test_cadence_comes_from_schedules_md_not_the_manifest(self):
        self.write_table(table(
            "| dashboard | Dashboard | — | fixed-interval | daily | yes | — | — | — |\n"
        ))
        self._routine_state(Dashboard="never")
        overdue = heartbeat.overdue_for_brain(self.brain)
        self.assertEqual([o["routine"] for o in overdue], ["Dashboard"])
        self.assertEqual(overdue[0]["cadence_days"], 1)

    def test_manifest_no_longer_carries_a_cadence_column(self):
        manifest = heartbeat.parse_manifest()
        self.assertTrue(manifest)
        self.assertNotIn("Cadence", manifest[0])

    def test_routine_with_no_schedule_is_never_flagged(self):
        self.write_table(HEADER)
        self._routine_state(Dashboard="never", Triage="never")
        self.assertEqual(heartbeat.overdue_for_brain(self.brain), [])

    def test_poll_scheduled_routine_is_never_flagged(self):
        self.write_table(table(
            "| triage | Triage | — | poll | 15m | yes | — | — | — |\n"
        ))
        self._routine_state(Triage="never")
        self.assertEqual(heartbeat.overdue_for_brain(self.brain), [])

    def test_disabled_schedule_is_never_flagged(self):
        self.write_table(table(
            "| dashboard | Dashboard | — | fixed-interval | daily | no | — | — | — |\n"
        ))
        self._routine_state(Dashboard="never")
        self.assertEqual(heartbeat.overdue_for_brain(self.brain), [])

    def test_clock_timing_implies_a_daily_cadence(self):
        self.write_table(table(FIXED_ROW))
        self._routine_state(Dashboard="never")
        overdue = heartbeat.overdue_for_brain(self.brain)
        self.assertEqual(overdue[0]["cadence_days"], 1)

    def test_missing_schedules_file_is_reported_not_fatal_for_dashboard(self):
        self._routine_state(Dashboard="never")
        self.assertEqual(heartbeat.overdue_for_brain(self.brain), [])


class TestStarterScheduleExample(unittest.TestCase):
    """The shipped starter table must reproduce the manifest's due-check set.

    `protocols/examples/schedules.md` is what the Brain Template ships as a
    fresh Brain's `config/schedules.md` (ADR-0030's required bootstrap), so it
    has to keep Heartbeat working out of the box.
    """

    EXAMPLE = Path(__file__).parent.parent / "protocols" / "examples" / "schedules.md"

    def test_example_parses(self):
        scheds = schedules.parse_schedules(self.EXAMPLE)
        self.assertEqual(len(scheds), 18)

    def test_example_declares_no_jobs(self):
        scheds = schedules.parse_schedules(self.EXAMPLE)
        self.assertEqual([s.label for s in scheds if s.renders_job], [])

    def test_every_manifest_routine_has_a_schedule(self):
        scheds = schedules.parse_schedules(self.EXAMPLE)
        scheduled = {s.routine for s in scheds}
        manifest_routines = {row["Routine"] for row in heartbeat.parse_manifest()}
        self.assertEqual(manifest_routines - scheduled, set())

    def test_flags_only_implemented_heartbeat_checkable_routines(self):
        manifest = heartbeat.parse_manifest()
        scheds = schedules.parse_schedules(self.EXAMPLE)
        routine_state = {row["Routine"]: "never" for row in manifest}
        overdue = heartbeat.compute_overdue(manifest, routine_state, scheds)
        self.assertEqual(
            {item["routine"] for item in overdue},
            {"Triage", "Dashboard", "Version control", "Planning session", "Daily note",
             "Close daily note", "Compile", "Graduation check", "Rule learning",
             "Ticket normalization"},
        )


if __name__ == "__main__":
    unittest.main()
